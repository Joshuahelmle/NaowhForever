"""Write NaowhForever_Professions/Data/RecipeReagents.lua: the reagents of every recipe the Professions
RecipeData lists, and how many items a craft makes when it is more than one.

Both come from the Forever client's own tables, through the project's wago reader for wago.BUILD with
its hotfixes: SpellReagents (Reagent_0..7 with ReagentCount_0..7) and SpellEffect's create-item effect
(Effect 24), whose EffectBasePointsF is the number made; 0 there means one, as for the enchanting oils.
A recipe the tables give no reagents (Disenchant, Find Fish) is left out. Cached in
data/recipe_reagents.json; --offline writes from it.

Usage: python Tools/build/recipe_reagents.py [--offline]
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
import wago  # noqa: E402

RECIPES = paths.ROOT / "NaowhForever_Professions" / "Data" / "RecipeData.lua"
OUT = paths.ROOT / "NaowhForever_Professions" / "Data" / "RecipeReagents.lua"
CACHE = paths.DATA / "recipe_reagents.json"
SPELL = re.compile(r"\{ spell = (\d+),")
SLOTS = 8
CREATE_ITEM = "24"


def recipe_spells(source):
    return sorted({int(spell) for spell in SPELL.findall(source)})


def read_reagents(spells, rows):
    """Spell (as text) -> [item, count, ...] for each wanted spell."""
    wanted, found = set(spells), {}
    for row in rows:
        spell = int(row["SpellID"])
        if spell not in wanted:
            continue
        parts = []
        for i in range(SLOTS):
            item, count = int(row[f"Reagent_{i}"] or 0), int(row[f"ReagentCount_{i}"] or 0)
            if item > 0 and count > 0:
                parts += [item, count]
        if parts:
            found[str(spell)] = parts
    return found


def read_made(spells, rows):
    """Spell (as text) -> how many items one craft makes, for each wanted spell making more than one."""
    wanted, made = set(spells), {}
    for row in rows:
        spell = int(row["SpellID"])
        if spell in wanted and row["Effect"] == CREATE_ITEM:
            count = int(float(row["EffectBasePointsF"] or 0))
            if count > 1:
                made[str(spell)] = count
    return made


def load(offline):
    if offline:
        return json.loads(CACHE.read_text(encoding="utf-8"))
    spells = recipe_spells(RECIPES.read_bytes().decode("ascii"))
    data = {"reagents": read_reagents(spells, wago.table("SpellReagents")),
            "made": read_made(spells, wago.table("SpellEffect"))}
    CACHE.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    return data


def render(data):
    lines = [
        "-- RecipeReagents.lua: each recipe's reagents as item, count pairs, and made when a craft makes more "
        "than one, by spell ID, generated by Tools/build/recipe_reagents.py.",
        "local P = _G.NaowhForever.Professions",
        "",
        "P.RecipeReagents = {",
    ]
    for spell in sorted(data["reagents"], key=int):
        parts = ", ".join(str(n) for n in data["reagents"][spell])
        made = data["made"].get(spell)
        lines.append(f"    [{spell}] = {{ {parts}{f', made = {made}' if made else ''} }},")
    lines.extend(["}", ""])
    return "\r\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    data = load(args.offline)
    OUT.write_text(render(data), encoding="utf-8", newline="")
    print(f"{len(data['reagents'])} recipes, {len(data['made'])} making more than one -> {OUT.name}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
